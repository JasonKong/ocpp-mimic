#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md from the third-party packages ocpp-mimic ships.
// With --check it writes nothing and fails when the file is out of date or a
// shipped package's license is not on the allow list.
//
// What ships: the engine's npm dependencies with theirs (installed next to the
// published package), and the parts of Vue that the Web UI bundle contains.
import { existsSync, readdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT = join(root, 'THIRD_PARTY_NOTICES.md');

/** Licenses a shipped package may have. */
const ALLOWED = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '0BSD']);

/** Vue's runtime, which Vite bundles into the Web UI (its compilers are build-time only). */
const WEB_BUNDLE = [
  'vue',
  '@vue/runtime-dom',
  '@vue/runtime-core',
  '@vue/reactivity',
  '@vue/shared',
];

const readJson = (file) => JSON.parse(readFileSync(file, 'utf8'));

/** Finds a dependency the way Node does: node_modules folders from `dir` upwards. */
function locate(name, dir) {
  for (let current = dir; ; current = dirname(current)) {
    if (basename(current) !== 'node_modules') {
      const candidate = join(current, 'node_modules', name);
      if (existsSync(join(candidate, 'package.json'))) return realpathSync(candidate);
    }
    if (dirname(current) === current) throw new Error(`cannot find ${name} from ${dir}`);
  }
}

function licenseText(dir) {
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  return file === undefined ? undefined : readFileSync(join(dir, file), 'utf8').trim();
}

/** Every package reachable from `names` (through dependencies `follow` accepts), by name and version. */
function collect(names, from, follow, how, found) {
  for (const name of names.filter(follow)) {
    const dir = locate(name, from);
    const manifest = readJson(join(dir, 'package.json'));
    const key = `${manifest.name}@${manifest.version}`;
    if (found.has(key)) continue;
    const license =
      typeof manifest.license === 'string' ? manifest.license : manifest.license?.type;
    found.set(key, {
      name: manifest.name,
      version: manifest.version,
      license,
      how,
      text: licenseText(dir),
    });
    collect(Object.keys(manifest.dependencies ?? {}), dir, follow, how, found);
  }
}

const engine = readJson(join(root, 'packages/engine/package.json'));
const found = new Map();
collect(
  Object.keys(engine.dependencies ?? {}).filter((name) => !name.startsWith('@ocpp-mimic/')),
  join(root, 'packages/engine'),
  () => true,
  'npm dependency',
  found,
);
collect(
  ['vue'],
  join(root, 'apps/web'),
  (name) => WEB_BUNDLE.includes(name),
  'bundled in the Web UI',
  found,
);

const packages = [...found.values()].sort((a, b) => a.name.localeCompare(b.name));
const problems = packages
  .filter((p) => !ALLOWED.has(p.license))
  .map((p) => `${p.name}@${p.version}: license ${p.license ?? 'missing'} is not allowed`);

const lines = [
  '# Third-party notices',
  '',
  'ocpp-mimic is licensed under the Business Source License 1.1 ([LICENSE](LICENSE)). It ships the third-party material below, each under its own license.',
  '',
  'This file is generated by `pnpm notices` from the installed packages; CI checks it with `pnpm notices:check`.',
  '',
  '## OCA OCPP JSON schemas',
  '',
  "`packages/engine/oca-schemas/` holds the Open Charge Alliance's official JSON Schema files for OCPP 1.6, the OCPP 1.6 Security Whitepaper, OCPP 2.0.1 and OCPP 2.1, © 2010 – 2026 Open Charge Alliance. They are shipped unchanged under the [Creative Commons Attribution-NoDerivatives 4.0 International Public License](https://creativecommons.org/licenses/by-nd/4.0/legalcode). The Business Source License does not apply to them. [Their README](packages/engine/oca-schemas/README.md) names the source, date and checksums of each set.",
  '',
  '## npm packages',
  '',
  '| Package | Version | License | Shipped as |',
  '| --- | --- | --- | --- |',
  ...packages.map((p) => `| ${p.name} | ${p.version} | ${p.license} | ${p.how} |`),
  '',
];
for (const p of packages) {
  lines.push(`### ${p.name} ${p.version}`, '');
  if (p.text === undefined) {
    lines.push(`The package has no license file; its package.json names ${p.license}.`, '');
  } else {
    lines.push('```text', p.text, '```', '');
  }
}
const content = lines.join('\n');

if (process.argv.includes('--check')) {
  if (!existsSync(OUTPUT) || readFileSync(OUTPUT, 'utf8') !== content) {
    problems.push('THIRD_PARTY_NOTICES.md is out of date: run `pnpm notices`');
  }
  if (problems.length > 0) {
    for (const problem of problems) console.error(problem);
    process.exit(1);
  }
  console.log(`THIRD_PARTY_NOTICES.md is up to date: ${packages.length} packages, all allowed`);
} else {
  writeFileSync(OUTPUT, content);
  for (const problem of problems) console.error(problem);
  console.log(`wrote THIRD_PARTY_NOTICES.md: ${packages.length} packages`);
  if (problems.length > 0) process.exit(1);
}
